        ("春季开学与通勤", "校园周边店围绕返校后的日常吃饭、新生认路与同学结伴；写字楼店围绕返工后的固定午餐选择。开学日期按附近学校核对，不全店套学生主题。", [(8, "三八节")]),
        ("春游与五一预热", "清明短途出游带动商圈、景点周边用餐；提前准备五一门店路线、营业时间与附近游逛内容。社区店保留周末家庭用餐主线。", []),
