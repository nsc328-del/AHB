        ("618与毕业季", "校园店做毕业前再吃一顿、同学聚餐；商圈店结合端午出游。618关注本地生活与外卖平台实际活动，参加后再宣传券包、有效期和使用门店。", [(18, "618")]),
        ("暑期与夏季外卖", "暑期商圈店面向出游家庭，校园店关注留校学生；写字楼店保留午餐与外卖需求。围绕实际在售搭配、取餐方式组织内容，不把高温直接写成销量增长。", []),
